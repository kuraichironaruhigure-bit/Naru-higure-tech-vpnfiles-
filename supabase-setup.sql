-- Run this entire script in Supabase SQL Editor.
-- It creates a private storage bucket and a review queue.
create table if not exists public.vpn_submissions (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  uploader text default '',
  file_name text not null,
  file_path text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);

alter table public.vpn_submissions enable row level security;

-- Anyone may submit a pending record. Public visitors can only read approved records.
drop policy if exists "public submit pending" on public.vpn_submissions;
create policy "public submit pending" on public.vpn_submissions
for insert to anon, authenticated
with check (status = 'pending');

drop policy if exists "public read approved" on public.vpn_submissions;
create policy "public read approved" on public.vpn_submissions
for select to anon, authenticated
using (status = 'approved');

-- Admins are authenticated users whose app_metadata.role is "admin".
drop policy if exists "admins read all submissions" on public.vpn_submissions;
create policy "admins read all submissions" on public.vpn_submissions
for select to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "admins update submissions" on public.vpn_submissions;
create policy "admins update submissions" on public.vpn_submissions
for update to authenticated
using ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin')
with check ((auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('vpn-files', 'vpn-files', false, 10485760, null)
on conflict (id) do update
set allowed_mime_types = null,
    file_size_limit = 10485760,
    public = false;

-- Public users may upload files to the private bucket.
drop policy if exists "public upload vpn files" on storage.objects;
create policy "public upload vpn files" on storage.objects
for insert to anon, authenticated
with check (bucket_id = 'vpn-files');

-- Approved files can be downloaded only via signed URLs generated by the app.
drop policy if exists "public read approved vpn files" on storage.objects;
create policy "public read approved vpn files" on storage.objects
for select to anon, authenticated
using (
  bucket_id = 'vpn-files'
  and exists (
    select 1 from public.vpn_submissions s
    where s.file_path = storage.objects.name
      and s.status = 'approved'
  )
);

-- Admins can view/download files in the private bucket.
drop policy if exists "admins read vpn files" on storage.objects;
create policy "admins read vpn files" on storage.objects
for select to authenticated
using (bucket_id = 'vpn-files' and (auth.jwt() -> 'app_metadata' ->> 'role') = 'admin');

